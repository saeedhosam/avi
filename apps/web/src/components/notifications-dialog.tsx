"use client";

import { useState } from "react";
import {
  BellRing,
  CheckCheck,
  Clock,
  DoorOpen,
  KeyRound,
  Luggage,
  Radio,
  Ticket,
  XCircle,
} from "lucide-react";
import { useApp } from "@/lib/store";
import { ALERT_META, cn, formatAlertTimestamp } from "@/lib/utils";
import { Button, EmptyState, Modal } from "./ui";

const alertIconMap = {
  GATE_CHANGE: DoorOpen,
  DELAY: Clock,
  BOARDING: Ticket,
  CANCELLATION: XCircle,
  BAGGAGE: Luggage,
} as const;

export function NotificationsDialog({
  open,
  onClose,
}: {
  open: boolean;
  onClose: () => void;
}) {
  const {
    alerts,
    unreadAlertCount,
    markAlertRead,
    markAllAlertsRead,
    enableBrowserNotifications,
    enableWebPush,
    notificationPermission,
    webPushSupported,
    webPushConfigured,
    webPushSubscribed,
    offlineMode,
  } = useApp();

  const [pushBusy, setPushBusy] = useState(false);
  const [pushMessage, setPushMessage] = useState<string | null>(null);

  return (
    <Modal
      open={open}
      onClose={onClose}
      title="Flight alerts & push"
      subtitle="Alerts generated by real status changes"
      icon={<BellRing className="size-4" />}
      size="lg"
      footer={
        <>
          <Button variant="ghost" size="sm" onClick={onClose}>
            Close
          </Button>
          {unreadAlertCount > 0 && (
            <Button size="sm" onClick={markAllAlertsRead}>
              <CheckCheck className="size-3.5" /> Mark all read
            </Button>
          )}
        </>
      }
    >
      <div className="space-y-4">
        <div className="rounded-xl border border-line bg-surface-2 p-3.5">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div className="flex items-center gap-2">
              <KeyRound className="size-4 text-accent" />
              <span className="label-caps text-ink">Push registration</span>
            </div>
            <div className="flex items-center gap-2">
              <span
                className={cn(
                  "size-1.5 rounded-full",
                  offlineMode ? "bg-delayed" : "bg-landed",
                )}
              />
              <span className="text-[10px] font-semibold text-muted">
                {offlineMode ? "Offline" : "Connected"}
              </span>
            </div>
          </div>

          {webPushSubscribed ? (
            <p className="mt-2 rounded-lg border border-landed/30 bg-landed/10 px-2.5 py-2 text-[10px] font-semibold text-landed">
              <KeyRound className="mr-1 inline size-3" /> Push enabled on this device
              — alerts arrive even with the app closed.
            </p>
          ) : !webPushSupported || !webPushConfigured ? (
            <p className="mt-2 rounded-lg border border-dashed border-line px-2.5 py-2 text-[10px] leading-relaxed text-subtle">
              {webPushSupported
                ? "Web Push isn't connected in this build yet. In-app alerts still work."
                : "This browser doesn't support Web Push. In-app alerts still work."}
            </p>
          ) : (
            <div className="mt-2 space-y-1">
              {pushMessage && (
                <p className="rounded-lg border border-delayed/30 bg-delayed/10 px-2.5 py-1.5 text-[10px] text-muted">
                  {pushMessage}
                </p>
              )}
              <Button
                size="sm"
                variant="outline"
                disabled={pushBusy}
                onClick={async () => {
                  setPushBusy(true);
                  setPushMessage(null);
                  try {
                    await enableWebPush();
                  } finally {
                    setPushBusy(false);
                  }
                }}
              >
                <KeyRound className="size-3.5" />
                {pushBusy ? "Connecting…" : "Enable push on this device"}
              </Button>
            </div>
          )}

          <div className="mt-3 flex flex-wrap items-center justify-between gap-2">
            <div className="flex items-center gap-2 text-[11px] text-muted">
              <Radio className="size-3.5 text-accent" />
              In-app notifications:{" "}
              <span className="font-semibold text-ink">{notificationPermission}</span>
            </div>
            <Button size="sm" variant="ghost" onClick={enableBrowserNotifications}>
              <BellRing className="size-3.5" />
              In-app only
            </Button>
          </div>
        </div>

        <div className="space-y-2">
          <div className="flex items-center justify-between">
            <span className="label-caps text-subtle">
              Alert inbox · {unreadAlertCount} unread
            </span>
            <span className="flex items-center gap-1 text-[9px] font-semibold text-landed">
              <span className="size-1.5 animate-pulse-dot rounded-full bg-landed" />
              Live status changes
            </span>
          </div>

          {!alerts.length ? (
            <EmptyState
              icon={<BellRing className="size-5" />}
              title="No alerts yet"
              description="Track or favorite a live flight. When a gate change, delay, boarding call, cancellation, or baggage update is reported, a real alert appears here."
            />
          ) : (
            <div className="space-y-2">
              {alerts.map((alert) => {
                const meta = ALERT_META[alert.type];
                const AlertIcon = alertIconMap[alert.type];
                return (
                  <button
                    key={alert.id}
                    onClick={() => markAlertRead(alert.id)}
                    className={cn(
                      "flex w-full items-start gap-3 rounded-xl border p-3 text-left transition-colors",
                      alert.isRead
                        ? "border-line/60 bg-surface-2/50"
                        : "border-line bg-surface-2 hover:border-accent/40",
                    )}
                  >
                    <span
                      className="mt-0.5 flex size-8 shrink-0 items-center justify-center rounded-lg border"
                      style={{
                        color: meta.color,
                        backgroundColor: `${meta.color}14`,
                        borderColor: `${meta.color}44`,
                      }}
                    >
                      <AlertIcon className="size-4" />
                    </span>
                    <span className="min-w-0 flex-1">
                      <span className="flex flex-wrap items-center gap-2">
                        <span
                          className={cn(
                            "text-xs font-bold",
                            alert.isRead ? "text-muted" : "text-ink",
                          )}
                        >
                          {alert.title}
                        </span>
                        {!alert.isRead && (
                          <span className="size-1.5 rounded-full bg-accent" />
                        )}
                      </span>
                      <span className="mt-0.5 block text-[11px] leading-relaxed text-muted">
                        {alert.message}
                      </span>
                      <span className="mt-1 flex items-center gap-2 text-[10px] text-subtle">
                        <span className="font-mono font-semibold text-accent">
                          {alert.flightNumber}
                        </span>
                        <span>·</span>
                        <span>{formatAlertTimestamp(alert.timestamp)}</span>
                      </span>
                    </span>
                  </button>
                );
              })}
            </div>
          )}
        </div>

        <p className="rounded-xl border border-dashed border-line px-3 py-2 text-[10px] leading-relaxed text-subtle">
          Alerts are generated by comparing successive live status
          snapshots of your saved flights — never fabricated, never test fired.
        </p>
      </div>
    </Modal>
  );
}
